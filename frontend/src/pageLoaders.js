export function prefetchPageForRoute(path) {
  const route = path.startsWith('/admin/users/') ? '/admin/users' : path;
  const loader = pageLoaders[ROUTE_PAGES[route]];
  if (!loader) return;

  const connection = typeof navigator !== 'undefined' ? navigator.connection : null;
  if (connection?.saveData || connection?.effectiveType === 'slow-2g') return;
  loader().catch(() => {});
}
